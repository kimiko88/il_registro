function updateLocales() {
  const i18nDir = path.resolve('src/i18n');
  
  for (const loc of locales) {
    const filePath = path.join(i18nDir, loc, 'index.js');
    if (!fs.existsSync(filePath)) {
      console.warn(`File not found: ${filePath}`);
      continue;
    }
    
    let content = fs.readFileSync(filePath, 'utf8');
    
    // Check if textbooksAie already exists
    if (content.includes('"textbooksAie"') || content.includes('textbooksAie:')) {
      console.log(`Locale ${loc} already contains textbooksAie, skipping...`);
      continue;
    }
    
    const locTranslations = translations[loc] || translations['en-US'];
    
    // Find the last closing brace '}'
    const lastBraceIndex = content.lastIndexOf('}');
    if (lastBraceIndex === -1) {
      console.error(`Could not find closing brace in ${filePath}`);
      continue;
    }
    
    // Build JSON for the new namespaces
    const newKeysObj = {
      textbooksAie: locTranslations.textbooksAie,
      dualSign: locTranslations.dualSign,
      classFormation: locTranslations.classFormation,
      middleSchoolExam: locTranslations.middleSchoolExam,
      religionAlternative: locTranslations.religionAlternative,
      familyDesk: locTranslations.familyDesk,
      pctoCompanyTutor: locTranslations.pctoCompanyTutor,
      schoolElections: locTranslations.schoolElections,
      helpDesk: locTranslations.helpDesk,
      agidProtocol: locTranslations.agidProtocol
    };
    
    let jsonString = JSON.stringify(newKeysObj, null, 2);
    // Strip outer braces
    jsonString = jsonString.trim();
    if (jsonString.startsWith('{')) {
      jsonString = jsonString.substring(1);
    }
    if (jsonString.endsWith('}')) {
      jsonString = jsonString.substring(0, jsonString.length - 1);
    }
    jsonString = jsonString.trim();
    
    // Insert before the last closing brace with a preceding comma
    const beforeBrace = content.substring(0, lastBraceIndex).trimEnd();
    const needsComma = !beforeBrace.endsWith(',');
    
    const updatedContent = `${beforeBrace}${needsComma ? ',' : ''}\n  ${jsonString}\n}\n`;
    fs.writeFileSync(filePath, updatedContent, 'utf8');
    console.log(`Successfully updated ${loc} with all commercial features!`);
  }
}

updateLocales();
